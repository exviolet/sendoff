// Замена домашнего каталога на `~`. Чистая функция — тестируется отдельно.
//
// Не система редактирования приватных данных и не пытается ею быть: отчёт вставляют
// в публичную issue, и убрать оттуда имя пользователя из путей — минимум приличия.
// Всё остальное (хостнеймы, имена проектов в путях воркспейсов) остаётся как есть:
// без них отчёт перестаёт быть отчётом.

export function sanitizeHome(text: string, home: string | null): string {
  if (!home) return text;
  // Хвостовой слэш нормализуем, иначе `/home/u/` дал бы `~.local/...` без разделителя.
  const root = home.endsWith("/") ? home.slice(0, -1) : home;
  // Пустой или корневой home не заменяем: `/` превратил бы весь текст в кашу из `~`.
  if (root === "" || root === "/") return text;
  return text.split(root).join("~");
}
